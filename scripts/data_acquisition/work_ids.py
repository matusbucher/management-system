from __future__ import annotations

from pathlib import Path
from typing import Iterable

_HEADER = "# Cellar work IDs, one per line (the text after '#' is a comment). Generated by scripts/data_acquisition/gather_work_ids.py"


def write_work_ids(
    path: Path,
    entries: Iterable[tuple[str, str]]
) -> None:
    """
    Write work IDs to a text file with one ID per line, each followed by a comment.

    The file is read by ``src.etlpipe.work_ids.read_work_ids``.

    Args:
        path (Path): The file to write; missing parent directories are created.
        entries (Iterable[tuple[str, str]]): Pairs of (work ID, comment).
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [_HEADER] + [f"{work_id}  # {comment}" if comment else work_id for work_id, comment in entries]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
